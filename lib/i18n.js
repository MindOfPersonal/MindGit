/**
 * Vertaal een key naar de gevraagde taal. Fallbacks: key → nl → '?key?'.
 */
function t(key, lang) {
  lang = SUPPORTED_LANGS.includes(lang) ? lang : DEFAULT_LANG;
  const table = DICT[lang] || DICT[DEFAULT_LANG];
  if (Object.prototype.hasOwnProperty.call(table, key)) return table[key];
  // Fallback naar default language
  if (lang !== DEFAULT_LANG && Object.prototype.hasOwnProperty.call(DICT[DEFAULT_LANG], key)) {
    return DICT[DEFAULT_LANG][key];
  }
  return '? ' + key + ' ?';
}

